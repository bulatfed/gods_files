# ══════════════════════════════════════════════════════════════════
# ЭТАП 1. СОЗДАНИЕ И ДОСТУП К ЭЛЕМЕНТАМ
# ══════════════════════════════════════════════════════════════════

# ─── 1.1 Создание словаря ─────────────────────────────────────────

d = {"a": 1, "b": 2}                    # литерал — самый частый способ
d = dict(a=1, b=2)                      # через dict(), ключи как имена
d = dict([("a", 1), ("b", 2)])          # из списка пар
d = dict.fromkeys(["a", "b"], 0)        # {"a": 0, "b": 0} — одинаковые значения
d = {x: x**2 for x in range(4)}         # генератор: {0: 0, 1: 1, 2: 4, 3: 9}

empty = {}                              # пустой словарь


# ─── 1.2 Доступ к элементам ───────────────────────────────────────

d = {"name": "Иван", "age": 25}

print(d["name"])            # "Иван"  ← если ключа НЕТ → KeyError
print(d["age"])             # 25

print(d.get("name"))        # "Иван"
print(d.get("salary"))      # None    ← не падает
print(d.get("salary", 0))   # 0       ← значение по умолчанию

# Правило: d[key] падает, d.get(key) — не падает.


# ─── 1.3 Проверка наличия ключа ───────────────────────────────────

d = {"a": 1, "b": 2}

print("a" in d)             # True   ← проверяет КЛЮЧИ, не значения
print("z" in d)             # False
print(1 in d)               # False  ← 1 это значение, не ключ
print("z" not in d)         # True


# ─── 1.4 Длина и пустота ──────────────────────────────────────────

d = {"a": 1, "b": 2, "c": 3}
empty = {}

print(len(d))               # 3      ← количество пар
print(bool(d))              # True   ← непустой → True
print(bool(empty))          # False  ← пустой → False

if empty:                   # пустой → False → идём в else
    print("не пусто")
else:
    print("пусто")          # напечатает это

# not d — «пустой ли?»:
print(not empty)            # True   ← пустой
print(not d)                # False  ← непустой


# ─── 1.5 Что может быть ключом ────────────────────────────────────

d = {42: "число"}           # ок — int
d = {"строка": 1}           # ок — str
d = {(1, 2): "точка"}       # ок — tuple (неизменяемый)
d = {True: "да", False: "нет"}  # ок — bool

# d = {[1, 2]: "точка"}     # ❌ TypeError — list изменяемый
# d = {{"a": 1}: "x"}       # ❌ TypeError — dict изменяемый
# d = {{1, 2}: "x"}         # ❌ TypeError — set изменяемый

# Ключом может быть только НЕИЗМЕНЯЕМЫЙ (hashable) тип.


# ─── 1.6 Вложенные словари ────────────────────────────────────────

users = {
    "ivan": {"age": 25, "city": "Москва"},
    "olga": {"age": 30, "city": "Питер"},
}

print(users["ivan"]["age"])         # 25
print(users["olga"]["city"])        # "Питер"

# Добавить/изменить во вложенном:
users["ivan"]["age"] = 26
users["petya"] = {"age": 20, "city": "Казань"}


# ══════════════════════════════════════════════════════════════════
# ЭТАП 2. ДОБАВЛЕНИЕ, ИЗМЕНЕНИЕ, УДАЛЕНИЕ
# ══════════════════════════════════════════════════════════════════

# ─── 2.1 Добавление и изменение (одно действие!) ──────────────────

d = {"a": 1}
d["b"] = 2                  # ключа не было → ДОБАВИЛИ
d["a"] = 100                # ключ был → ИЗМЕНИЛИ
print(d)                    # {"a": 100, "b": 2}

# Присваивание по ключу работает И для добавления, И для изменения.


# ─── 2.2 Удаление ─────────────────────────────────────────────────

d = {"a": 1, "b": 2, "c": 3}

del d["a"]                  # удалить ключ
print(d)                    # {"b": 2, "c": 3}

val = d.pop("b")            # удалить И вернуть значение
print(val)                  # 2
print(d)                    # {"c": 3}

d.pop("z", None)            # безопасно — ключа нет → вернёт None
d.clear()                   # очистить весь словарь
print(d)                    # {}


# ─── 2.3 update — слить со словарём ───────────────────────────────

d = {"a": 1, "b": 2}
d.update({"b": 99, "c": 3})     # "b" перезапишется, "c" добавится
print(d)                        # {"a": 1, "b": 99, "c": 3}


# ─── 2.4 setdefault — достать ИЛИ создать ─────────────────────────

d = {"name": "Иван"}

print(d.setdefault("name", "неизвестно"))   # "Иван" — ключ есть, ничего не меняет
print(d.setdefault("age", 0))               # 0      — ключа нет → создал
print(d)                                    # {"name": "Иван", "age": 0}

# setdefault(key, default):
#   - если ключ есть → вернёт его значение, НЕ меняя словарь
#   - если ключа нет → создаст его со значением default и вернёт его


# ══════════════════════════════════════════════════════════════════
# ЭТАП 3. ПЕРЕБОР СЛОВАРЯ
# ══════════════════════════════════════════════════════════════════

d = {"a": 1, "b": 2, "c": 3}

# ─── 3.1 По ключам ────────────────────────────────────────────────

for k in d:                 # то же, что for k in d.keys():
    print(k, d[k])          # a 1, b 2, c 3


# ─── 3.2 По значениям ─────────────────────────────────────────────

for v in d.values():
    print(v)                # 1, 2, 3


# ─── 3.3 По парам (самый частый способ) ───────────────────────────

for k, v in d.items():
    print(k, v)             # a 1, b 2, c 3


# ─── 3.4 Что возвращают keys/values/items ─────────────────────────

print(d.keys())             # dict_keys(['a', 'b', 'c']) — спец. объект
print(d.values())           # dict_values([1, 2, 3])
print(d.items())            # dict_items([('a', 1), ('b', 2), ('c', 3)])

# Чтобы получить обычный список:
print(list(d.keys()))       # ['a', 'b', 'c']
print(list(d.values()))     # [1, 2, 3]
print(list(d.items()))      # [('a', 1), ('b', 2), ('c', 3)]


# ─── 3.5 Перебор по значениям с проверкой ─────────────────────────

d = {"a": "h", "b": "e", "c": "l"}

print("e" in d)             # False ← проверка по КЛЮЧАМ
print("e" in d.values())    # True  ← проверка по ЗНАЧЕНИЯМ


# ─── 3.6 Встроенные функции по значениям ──────────────────────────

d = {"x": 10, "y": 20, "z": 30}

print(min(d))               # 'x'  ← по КЛЮЧАМ
print(max(d))               # 'z'  ← по КЛЮЧАМ
print(sum(d.values()))      # 60   ← по ЗНАЧЕНИЯМ
print(min(d.values()))      # 10
print(max(d.values()))      # 30


# ══════════════════════════════════════════════════════════════════
# ЭТАП 4. ССЫЛКИ vs КОПИИ
# ══════════════════════════════════════════════════════════════════

# ─── 4.1 Ссылка (одно имя на двоих) ───────────────────────────────

a = {"x": 1}
b = a                       # b смотрит на ТОТ ЖЕ объект
b["y"] = 2
print(a)                    # {"x": 1, "y": 2} ← а! изменился


# ─── 4.2 Копия (независимый объект) ───────────────────────────────

a = {"x": 1}
b = a.copy()                # независимая ПОВЕРХНОСТНАЯ копия
b["y"] = 2
print(a)                    # {"x": 1} ← не тронут
print(b)                    # {"x": 1, "y": 2}


# ─── 4.3 Поверхностная vs глубокая ────────────────────────────────

import copy

a = {"x": [1, 2], "y": [3, 4]}

b = a.copy()                # поверхностная: вложенные списки ОБЩИЕ
b["x"].append(99)
print(a)                    # {"x": [1, 2, 99], ...} ← а! изменился

a = {"x": [1, 2], "y": [3, 4]}
c = copy.deepcopy(a)        # глубокая: вложенное тоже копируется
c["x"].append(99)
print(a)                    # {"x": [1, 2], ...} ← не тронут


# ══════════════════════════════════════════════════════════════════
# ЭТАП 5. ПОЛЕЗНЫЕ ПРИЁМЫ
# ══════════════════════════════════════════════════════════════════

# ─── 5.1 Счётчик вхождений (классика!) ────────────────────────────

text = "abracadabra"
counter = {}
for ch in text:
    counter[ch] = counter.get(ch, 0) + 1
print(counter)              # {"a": 5, "b": 2, "r": 2, "c": 1, "d": 1}


# ─── 5.2 Слияние словарей ─────────────────────────────────────────

a = {"x": 1}
b = {"y": 2}

c = {**a, **b}              # новый словарь, a и b целы
print(c)                    # {"x": 1, "y": 2}

a.update(b)                 # то же самое, но МЕНЯЕТ a
print(a)                    # {"x": 1, "y": 2}


# ─── 5.3 Инверсия словаря (ключ ↔ значение) ───────────────────────

d = {"a": 1, "b": 2}
inv = {v: k for k, v in d.items()}
print(inv)                  # {1: "a", 2: "b"}


# ─── 5.4 Генератор словаря ────────────────────────────────────────

words = ["кот", "собака", "дом"]
lengths = {w: len(w) for w in words}
print(lengths)              # {"кот": 3, "собака": 6, "дом": 3}


# ─── 5.5 Counter из collections ───────────────────────────────────

from collections import Counter

c = Counter("abracadabra")
print(c)                    # Counter({"a": 5, "b": 2, "r": 2, "c": 1, "d": 1})
print(c.most_common(2))     # [("a", 5), ("b", 2)] ← топ-2
print(c["a"])               # 5


